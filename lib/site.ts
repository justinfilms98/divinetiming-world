/**
 * Site-wide constants for SEO, metadata, and canonical URLs.
 * Phase 12 — SEO + Metadata + Social Sharing.
 */

export const SITE_NAME = 'Divine Timing';

/** Brand tagline already used as the default meta description. Do not invent alternatives. */
export const SITE_TAGLINE = 'Live, evolving, in motion.';

export const PRODUCTION_URL = 'https://divinetiming.world';

const VERCEL_ENV = process.env.VERCEL_ENV ?? process.env.NEXT_PUBLIC_VERCEL_ENV;

/** Preview/dev deployments must never be indexed or used as canonical. */
export const IS_PRODUCTION_SITE = VERCEL_ENV === 'production';

function resolveBaseUrl(): string {
  const explicit = process.env.NEXT_PUBLIC_SITE_URL;
  if (typeof explicit === 'string' && explicit.startsWith('http')) {
    return explicit.replace(/\/+$/, '');
  }
  // VERCEL_URL is the per-deployment *.vercel.app host; never canonical in production.
  if (IS_PRODUCTION_SITE) return PRODUCTION_URL;
  const deployment = process.env.VERCEL_URL ?? process.env.NEXT_PUBLIC_VERCEL_URL;
  if (deployment) return `https://${deployment}`;
  return PRODUCTION_URL;
}

export const BASE_URL = resolveBaseUrl();

/** Default 1200×630 share image, generated by app/opengraph-image.tsx. */
export const DEFAULT_OG_IMAGE = '/opengraph-image';

/** Build canonical URL for a path (e.g. '/events' → 'https://divinetiming.world/events'). */
export function canonicalUrl(path: string): string {
  const p = path.startsWith('/') ? path : `/${path}`;
  return `${BASE_URL}${p}`;
}

/** Ensure image URL is absolute for OpenGraph/Twitter. */
export function absoluteImageUrl(url: string | null | undefined): string | undefined {
  if (!url) return undefined;
  if (url.startsWith('http://') || url.startsWith('https://')) return url;
  return `${BASE_URL}${url.startsWith('/') ? url : `/${url}`}`;
}
